import { test, expect, type Page } from '@playwright/test'
import { buildings, CURRENT_YEAR } from '../src/data/history'

async function ready(page: Page) {
  await page.goto('./')
  await expect(page.locator('canvas[data-webgl="ready"]')).toBeVisible()
  await expect.poll(() => page.evaluate(() => window.__MJUTIME_DEBUG__?.().frame ?? 0)).toBeGreaterThan(2)
}
async function setYear(page: Page, year: number) {
  await page.getByRole('slider', { name: '시간 여행 연도' }).fill(String(year))
  await expect(page.getByTestId('current-year')).toHaveText(String(year))
}
async function model(page: Page, id: string) {
  return page.evaluate(id => window.__MJUTIME_DEBUG__?.().buildings.find(item => item.id === id), id)
}
test('real WebGL, scenarios A–F, sources, and camera interactions', async ({ page }, testInfo) => {
  const errors: string[] = []
  page.on('pageerror', error => errors.push(error.stack ?? error.message))
  page.on('console', message => { if (message.type() === 'error') errors.push(message.text()) })
  await ready(page)
  await expect(page.getByTestId('current-year')).toHaveText(String(CURRENT_YEAR))
  const initialGeometries = await page.evaluate(() => window.__MJUTIME_DEBUG__?.().geometries ?? 0)
  await expect.poll(async () => (await model(page, 'mcc'))?.scaleY).toBe(1)
  await expect.poll(() => page.evaluate(() => window.__MJUTIME_DEBUG__?.().calls ?? 0)).toBeGreaterThan(20)
  await page.screenshot({ path: `test-results/${testInfo.project.name}-present.png` })
  // Real orbit and zoom change the Three camera, not a DOM mock.
  const initial = await page.evaluate(() => window.__MJUTIME_DEBUG__?.().camera)
  const canvas = page.locator('canvas')
  const box = (await canvas.boundingBox())!
  if (testInfo.project.name === 'desktop') {
    await page.mouse.move(box.x + box.width * .75, box.y + box.height * .43)
    await page.mouse.down(); await page.mouse.move(box.x + box.width * .86, box.y + box.height * .51, { steps: 15 }); await page.mouse.up()
    await expect.poll(() => page.evaluate(() => window.__MJUTIME_DEBUG__?.().camera)).not.toEqual(initial)
    const rotated = await page.evaluate(() => window.__MJUTIME_DEBUG__?.().camera)
    await page.mouse.wheel(0, -200)
    await expect.poll(() => page.evaluate(() => window.__MJUTIME_DEBUG__?.().camera)).not.toEqual(rotated)
  } else {
    const session = await page.context().newCDPSession(page)
    const x = box.x + box.width * .2, y = box.y + box.height * .55
    await session.send('Input.dispatchTouchEvent', { type: 'touchStart', touchPoints: [{ x, y, id: 0 }] })
    for (let i = 1; i <= 8; i++) await session.send('Input.dispatchTouchEvent', { type: 'touchMove', touchPoints: [{ x: x + i * 8, y: y + i * 2, id: 0 }] })
    await session.send('Input.dispatchTouchEvent', { type: 'touchEnd', touchPoints: [] })
    await expect.poll(() => page.evaluate(() => window.__MJUTIME_DEBUG__?.().camera)).not.toEqual(initial)
    const rotated = await page.evaluate(() => window.__MJUTIME_DEBUG__?.().camera)
    await session.send('Input.dispatchTouchEvent', { type: 'touchStart', touchPoints: [{ x: x - 30, y, id: 0 }, { x: x + 30, y, id: 1 }] })
    for (let i = 1; i <= 8; i++) await session.send('Input.dispatchTouchEvent', { type: 'touchMove', touchPoints: [{ x: x - 30 - i * 4, y, id: 0 }, { x: x + 30 + i * 4, y, id: 1 }] })
    await session.send('Input.dispatchTouchEvent', { type: 'touchEnd', touchPoints: [] })
    await expect.poll(() => page.evaluate(() => window.__MJUTIME_DEBUG__?.().camera)).not.toEqual(rotated)
    await session.detach()
  }
  await page.getByRole('button', { name: '기본 시점으로' }).click()
  await setYear(page, 2010)
  await expect.poll(async () => (await model(page, 'mcc'))?.visible).toBe(false)
  await expect.poll(async () => (await model(page, 'library'))?.scaleY).toBe(1)
  await setYear(page, 2005)
  await expect.poll(async () => (await model(page, 'dorm'))?.visible).toBe(false)
  await setYear(page, 2006)
  await expect.poll(async () => (await model(page, 'dorm'))?.scaleY).toBe(1)
  const beforeFocus = await page.evaluate(() => window.__MJUTIME_DEBUG__?.().camera)
  const dormMarker = page.getByRole('button', { name: '2006년 인문캠퍼스 생활관 개관 사건 보기' })
  if (testInfo.project.name === 'mobile') await dormMarker.tap()
  else await dormMarker.click()
  await expect(page.getByRole('heading', { name: '인문캠퍼스 생활관 개관' })).toBeVisible()
  await expect(page.getByRole('link', { name: '명지대학교 공식 연혁' })).toHaveAttribute('href', /161\/subview.do/)
  await expect(page.getByRole('link', { name: '명지대학교 공식 연혁' })).toBeVisible()
  await expect.poll(() => page.evaluate(() => window.__MJUTIME_DEBUG__?.().camera)).not.toEqual(beforeFocus)
  await page.screenshot({ path: `test-results/${testInfo.project.name}-story.png` })
  await page.getByRole('button', { name: '캠퍼스 탐색으로' }).click()
  await page.getByRole('button', { name: '자연캠퍼스 용인' }).click()
  await expect(page.getByTestId('current-year')).toHaveText('2006')
  await setYear(page, 2007)
  await expect.poll(async () => (await model(page, 'science'))?.visible).toBe(false)
  await setYear(page, 2008)
  await expect.poll(async () => (await model(page, 'science'))?.scaleY).toBe(1)
  await expect.poll(async () => (await model(page, 'chapel'))?.scaleY).toBe(1)
  await expect(page.getByRole('button', { name: '2008년 차세대과학관 개관 사건 보기' })).toBeVisible()
  await setYear(page, 1988)
  await page.getByRole('button', { name: '다음 사건' }).click()
  await expect(page.getByTestId('current-year')).toHaveText('1989')
  await expect(page.getByRole('button', { name: '1989년 두 캠퍼스, 각자의 전문성으로 사건 보기' })).toHaveClass(/current/)
  for (const year of [2008, 1948, CURRENT_YEAR, 2007, 2008, 1983, CURRENT_YEAR, 2007]) await setYear(page, year)
  await expect.poll(async () => (await model(page, 'science'))?.visible).toBe(false)
  await expect.poll(async () => (await model(page, 'chapel'))?.visible).toBe(false)
  expect((await page.evaluate(() => window.__MJUTIME_DEBUG__?.().buildings))?.length).toBe(buildings.filter(building=>building.campus==='nature').length)
  await setYear(page, 1978)
  await expect(page.getByText('아직 이곳에 닿기 전의 이야기')).toBeVisible()
  await expect.poll(() => page.evaluate(() => window.__MJUTIME_DEBUG__?.().buildings.every(building => !building.visible))).toBe(true)
  await setYear(page, CURRENT_YEAR)
  await expect.poll(async () => (await model(page, 'chapel'))?.scaleY).toBe(1)
  await page.screenshot({ path: `test-results/${testInfo.project.name}-nature.png` })
  await page.getByRole('button', { name: '역사 목록' }).click()
  await page.getByRole('button', { name: /2010.*지식을 잇는 방목학술정보관/ }).click()
  await expect(page.getByRole('button', { name: '인문캠퍼스 서울' })).toHaveAttribute('aria-pressed', 'true')
  await expect(page.getByTestId('current-year')).toHaveText('2010')
  await page.getByRole('button', { name: '사건 패널 닫기' }).click()
  // Campus switches must release the old scene's GPU geometry.
  await expect.poll(() => page.evaluate(() => window.__MJUTIME_DEBUG__?.().geometries ?? Infinity), { timeout: 15_000 }).toBeLessThanOrEqual(initialGeometries + 3)
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true)
  expect(errors).toEqual([])
})

test('playback, resizing, labels, and keyboard navigation', async ({ page }) => {
  await ready(page)
  await setYear(page, 2005)
  await page.getByRole('button', { name: '자동 시간 여행 재생' }).click()
  await expect(page.getByTestId('current-year')).not.toHaveText('2005')
  await page.getByRole('button', { name: '시간 여행 일시정지' }).click()
  const paused = await page.getByTestId('current-year').textContent()
  await page.waitForTimeout(950)
  await expect(page.getByTestId('current-year')).toHaveText(paused!)
  await page.getByRole('button', { name: '건물 이름 표시' }).click()
  await expect(page.locator('.building-label')).toHaveCount(0)
  await page.getByRole('button', { name: '건물 이름 표시' }).click()
  await page.setViewportSize({ width: 820, height: 850 })
  await expect(page.locator('canvas')).toBeVisible()
  await page.getByRole('slider').focus(); await page.keyboard.press('ArrowRight')
  await expect(page.getByTestId('current-year')).toHaveText(String(Number(paused) + 1))
  await page.getByRole('button', { name: '역사 목록' }).click()
  await page.keyboard.press('Escape')
  await expect(page.getByRole('region', { name: '전체 역사 목록' })).toHaveCount(0)
})

test('WebGL unavailable still supports text-based exploration', async ({ page }) => {
  await page.addInitScript(() => { HTMLCanvasElement.prototype.getContext = (() => null) as typeof HTMLCanvasElement.prototype.getContext })
  await page.goto('./')
  await expect(page.getByText('텍스트로 떠나는 시간 여행')).toBeVisible()
  await expect(page.locator('canvas')).toHaveCount(0)
  await page.getByRole('button', { name: /2006.*인문캠퍼스 생활관 개관/ }).click()
  await expect(page.getByRole('heading', { name: '인문캠퍼스 생활관 개관' })).toBeVisible()
  await expect(page.getByRole('link', { name: '명지대학교 공식 연혁' })).toBeVisible()
})
